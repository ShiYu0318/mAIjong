/**
 * Lightweight i18n (SPEC P11-6): Traditional Chinese is the source language and the key;
 * English strings live in EN. Missing entries fall back to Chinese.
 *
 *   const t = useT();
 *   t("座位 {n}", { n: 2 })
 */
import { useCallback } from "react";
import { create } from "zustand";

export type Locale = "zh-TW" | "en";
const STORAGE_KEY = "maijong.locale";

interface LocaleState {
  locale: Locale;
  setLocale: (l: Locale) => void;
  load: () => void;
}

export const useLocale = create<LocaleState>((set) => ({
  locale: "zh-TW",
  setLocale: (locale) => {
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      /* private mode */
    }
    if (typeof document !== "undefined") document.documentElement.lang = locale === "en" ? "en" : "zh-Hant-TW";
    set({ locale });
  },
  load: () => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "en" || saved === "zh-TW") {
        document.documentElement.lang = saved === "en" ? "en" : "zh-Hant-TW";
        set({ locale: saved });
      }
    } catch {
      /* ignore */
    }
  },
}));

export type Vars = Record<string, string | number>;

const fill = (s: string, vars?: Vars) =>
  vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : s;

export function translate(zh: string, vars?: Vars, locale: Locale = useLocale.getState().locale): string {
  return fill(locale === "en" ? EN[zh] ?? zh : zh, vars);
}

/** BCP 47 tag for dates and numbers in the current language. */
export const dateLocale = (locale: Locale = useLocale.getState().locale) => (locale === "en" ? "en-US" : "zh-TW");

const SEAT_NUMBERS: Record<string, string> = { "一": "1", "二": "2", "三": "3", "四": "4" };

/** Names the server makes up (bots, house agents, guests), shown in the current language;
 * names people chose are left alone. */
export function localName(name: string, locale: Locale = useLocale.getState().locale): string {
  if (locale !== "en" || !name) return name;
  let m = name.match(/^電腦([一二三四])號（(.+)）$/);
  if (m) return `Bot ${SEAT_NUMBERS[m[1]]} (${translate(m[2], undefined, "en")})`;
  m = name.match(/^官方 Bot (.+)$/);
  if (m) return `House bot ${translate(m[1], undefined, "en")}`;
  m = name.match(/^訪客(\d+)$/);
  if (m) return `Guest${m[1]}`;
  return name;
}

/** Re-renders the caller when the locale changes. */
export function useT() {
  const locale = useLocale((s) => s.locale);
  return useCallback((zh: string, vars?: Vars) => translate(zh, vars, locale), [locale]);
}

